-- IMPORTANTE: este job solo marca vencimientos.
-- El envío de WhatsApp/correo se realiza mediante la Edge Function.
select cron.schedule(
  'pasillo-marcar-vencidos',
  '5 3 * * *',
  $$select public.mark_expired_subscriptions();$$
)
where not exists (
  select 1 from cron.job where jobname='pasillo-marcar-vencidos'
);

